-- qua màn hình admin CRUD ở CMS thay cho danh sách hardcode của GĐ3
-- (HardcodedTriageKeywordSource). group_code là 1 trong 13 nhóm cố định (xem
-- TriageKeywordGroup) - không CRUD được nhóm, chỉ CRUD từ khóa trong nhóm.
CREATE TABLE triage_keywords (
    id          BIGSERIAL PRIMARY KEY,
    group_code  VARCHAR(50) NOT NULL,
    keyword     VARCHAR(200) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (group_code, keyword)
);

CREATE INDEX idx_triage_keywords_group ON triage_keywords(group_code);

